import assert from 'node:assert/strict';
import { scheduleFor, actualBalance, forecast, monthlyBudget, setPurchaseCancelled, cashEntries } from '../model.mjs';
import { planData, createBackup, parseBackup } from '../backup.mjs';
let checks=0;const eq=(a,b)=>{assert.deepEqual(a,b);checks++};
const make=()=>planData({showDemo:false,customExpenses:[{id:'buy',title:'Покупка',category:'Еда',amount:-100,date:'2026-11-18'}],payments:{buy:'2026-11-18'},snapshot:{date:'2026-11-18',amount:1000,paidIds:[]},budgets:{'2026-11':{food:1000}}});
const item=s=>scheduleFor(s).find(({id})=>id==='buy');
const balance=(s,date)=>forecast(s,date.slice(0,7)).ledger.get(date).balance;
const change=(s,value,date='2026-11-18')=>setPurchaseCancelled(s,item(s),value,date,'adjust-'+s.operationChanges.length);
let s=make();
eq(actualBalance(s,'2026-11-18'),900);
eq(balance(s,'2026-11-19'),900);
eq(change(s,true),true);
eq(actualBalance(s,'2026-11-18'),1000);
eq(balance(s,'2026-11-19'),1000);
eq(forecast(s).summary.income,0);
eq(forecast(s).summary.expenses,0);
eq(monthlyBudget(s,'2026-11')[0].spent,0);
eq(monthlyBudget(s,'2026-11')[0].planned,0);
eq(change(s,true),false);
eq(s.operationChanges.length,1);
eq(change(s,false),true);
eq(actualBalance(s,'2026-11-18'),900);
eq(balance(s,'2026-11-19'),900);
eq(monthlyBudget(s,'2026-11')[0].spent,100);
s=make();s.snapshot={date:'2026-11-18',amount:900,paidIds:['buy']};
eq(change(s,true),true);
eq(actualBalance(s,'2026-11-18'),1000);
eq(balance(s,'2026-11-19'),1000);
s.snapshot={date:'2026-11-18',amount:1000,paidIds:scheduleFor(s).flatMap(cashEntries).map(({id})=>id)};
eq(change(s,false),true);
eq(actualBalance(s,'2026-11-18'),900);
eq(balance(s,'2026-11-19'),900);
s=make();s.payments={};s.customExpenses[0].date='2026-11-19';
eq(balance(s,'2026-11-19'),900);
eq(change(s,true),true);
eq(actualBalance(s,'2026-11-18'),1000);
eq(balance(s,'2026-11-19'),1000);
eq(s.operationChanges.length,0);
change(s,false);eq(balance(s,'2026-11-19'),900);
s=make();s.customExpenses[0].repeat='daily';s.customExpenses[0].repeatEnd='2026-11-19';
eq(balance(s,'2026-11-19'),800);
change(s,true);
eq(actualBalance(s,'2026-11-18'),1000);
eq(balance(s,'2026-11-19'),900);
eq(scheduleFor(s).find(({id})=>id==='buy@2026-11-19').remaining,100);
eq(monthlyBudget(s,'2026-11')[0].planned,100);
s=make();s.customExpenses[0].repeat='daily';s.customExpenses[0].repeatEnd='2026-12-01';
s.payments={'buy@2026-12-01':'2026-11-18'};
eq(actualBalance(s,'2026-11-18'),900);
const future=scheduleFor(s,undefined,'2026-11').find(({id})=>id==='buy@2026-12-01');
eq(setPurchaseCancelled(s,future,true,'2026-11-18','change-future'),true);
eq(actualBalance(s,'2026-11-18'),1000);
const restored=parseBackup(JSON.stringify(createBackup(s))).data;
eq(restored,s);
eq(forecast(restored,'2026-12').summary,forecast(s,'2026-12').summary);
eq(actualBalance(restored,'2026-11-18'),1000);
for(const version of [1,2]){
 const old=createBackup(make());old.schemaVersion=version;delete old.data.operationChanges;delete old.data.cancellations;
 if(version===1)delete old.data.budgets;
 eq(parseBackup(JSON.stringify(old)).data.cancellations,{});
 eq(parseBackup(JSON.stringify(old)).data.operationChanges,[]);
}
// Partial payments return only the amount actually entered; restoration keeps the remainder planned.
s=make();s.payments={};s.installments={buy:[{id:'part-one',date:'2026-11-18',amount:40}]};
eq(actualBalance(s,'2026-11-18'),960);
change(s,true);eq(actualBalance(s,'2026-11-18'),1000);eq(balance(s,'2026-11-19'),1000);
eq(parseBackup(JSON.stringify(createBackup(s))).data,s);
change(s,false);eq(actualBalance(s,'2026-11-18'),960);eq(balance(s,'2026-11-19'),900);
// A later refund preserves historical days and is counted once after a fresh balance checkpoint.
s=make();change(s,true,'2026-11-19');
eq(balance(s,'2026-11-18'),900);eq(balance(s,'2026-11-19'),1000);
eq(monthlyBudget(s,'2026-11')[0].spent,0);
s.snapshot={date:'2026-11-20',amount:1000,paidIds:[]};
change(s,false,'2026-11-21');eq(actualBalance(s,'2026-11-21'),900);eq(balance(s,'2026-11-22'),900);
eq(parseBackup(JSON.stringify(createBackup(s))).data,s);
s=make();change(s,true);
let bad=createBackup(s);bad.data.operationChanges[0].amount=200;
assert.throws(()=>parseBackup(JSON.stringify(bad)));checks++;
console.log(checks+' проверок отмены, восстановления, прогнозов, повторов и резервных копий пройдены.');
